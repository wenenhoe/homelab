"""Pull request descriptions in the shape Renovate writes them: a table of updates, release notes in `<details>`, then the configuration footer."""

FOOTER = """
---

### Configuration

📅 **Schedule**: Branch creation - "* 0-5 * * 1,4" in timezone Asia/Singapore, Automerge - At any time (no schedule defined).

🚦 **Automerge**: Disabled by config. Please merge this manually once you are satisfied.

♻ **Rebasing**: Whenever PR is behind base branch, or you tick the rebase/retry checkbox.

---

 - [ ] <!-- rebase-check -->If you want to rebase/retry this PR, check this box

---

This PR was generated by [Mend Renovate](https://github.com/renovatebot/renovate). View the [repository job log](https://developer.mend.io/github/example/homelab).
<!--renovate-debug:abc123-->
"""


def body(name: str, old: str, new: str, notes: str = "") -> str:
    """A description for one update; `notes` is the text inside the release notes block, empty for an update that has none."""
    table = f"""This PR contains the following updates:

| Package | Change | Age | Confidence |
|---|---|---|---|
| [{name}](https://github.com/{name}) | `{old}` → `{new}` | [![age](https://example.test/a.svg)](https://example.test/a) | ![c](https://example.test/c.svg) |
"""
    if not notes:
        return table + FOOTER
    return f"""{table}
---

### Release Notes

<details>
<summary>{name} ({name})</summary>

{notes}

</details>
{FOOTER}"""


