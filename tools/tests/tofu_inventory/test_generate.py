"""Tests for the Tofu-to-Ansible inventory generator."""

from __future__ import annotations

import json
import subprocess
from pathlib import Path
from types import SimpleNamespace

import pytest
import yaml
from tofu_inventory import generate

SERVICES = {"ip_address": "192.168.20.3", "admin_username": "svcadmin"}
PLAY = {"ip_address": "192.168.20.4", "admin_username": "playadmin"}


def hosts_json(**hosts: dict) -> str:
    return json.dumps(hosts)


class TestParseHosts:
    def test_accepts_entries_with_an_address_and_a_user(self):
        assert generate.parse_hosts(hosts_json(services=SERVICES)) == {"services": SERVICES}

    def test_accepts_no_hosts(self):
        assert generate.parse_hosts("{}") == {}

    @pytest.mark.parametrize(
        ("raw", "match"),
        [
            pytest.param("not json", "not JSON", id="not-json"),
            pytest.param("[]", "keyed by host name", id="list-instead-of-object"),
            pytest.param(hosts_json(**{"Services": SERVICES}), "valid inventory host name", id="uppercase-name"),
            pytest.param(hosts_json(**{"a b": SERVICES}), "valid inventory host name", id="name-with-space"),
            pytest.param(hosts_json(services={"ip_address": "192.168.20.3"}), "exactly", id="missing-user"),
            pytest.param(hosts_json(services={**SERVICES, "mac_address": "x"}), "exactly", id="extra-key"),
            pytest.param(hosts_json(services="192.168.20.3"), "exactly", id="entry-not-an-object"),
            pytest.param(hosts_json(services={**SERVICES, "ip_address": "192.168.20.300"}), "not an IPv4", id="bad-address"),
            pytest.param(hosts_json(services={**SERVICES, "ip_address": "fd00::3"}), "not an IPv4", id="ipv6-address"),
            pytest.param(hosts_json(services={**SERVICES, "admin_username": "svc admin"}), "valid login name", id="user-with-space"),
            pytest.param(hosts_json(services={**SERVICES, "admin_username": ""}), "valid login name", id="empty-user"),
        ],
    )
    def test_rejects(self, raw, match):
        with pytest.raises(generate.InventoryError, match=match):
            generate.parse_hosts(raw)


class TestRender:
    def test_maps_each_host_to_its_address_and_user(self):
        text = generate.render({"services": SERVICES})
        assert yaml.safe_load(text) == {"all": {"hosts": {"services": {"ansible_host": "192.168.20.3", "ansible_user": "svcadmin"}}}}

    def test_output_does_not_depend_on_input_order(self):
        assert generate.render({"services": SERVICES, "play": PLAY}) == generate.render({"play": PLAY, "services": SERVICES})

    def test_hosts_are_sorted_by_name(self):
        parsed = yaml.safe_load(generate.render({"services": SERVICES, "play": PLAY}))
        assert list(parsed["all"]["hosts"]) == ["play", "services"]

    def test_starts_with_the_do_not_edit_header(self):
        assert generate.render({}).startswith("# Generated by tools/tofu_inventory")

    def test_no_hosts_is_a_valid_inventory(self):
        assert yaml.safe_load(generate.render({})) == {"all": {"hosts": {}}}


class TestWriteAtomically:
    def test_replaces_the_file_and_leaves_no_temporary(self, tmp_path):
        out = tmp_path / "hosts.yaml"
        out.write_text("old")
        generate.write_atomically(out, "new")
        assert out.read_text() == "new"
        assert list(tmp_path.iterdir()) == [out]

    def test_keeps_the_old_file_when_the_write_fails(self, tmp_path, monkeypatch):
        out = tmp_path / "hosts.yaml"
        out.write_text("old")

        def fail(self, target):
            raise OSError("disk full")

        monkeypatch.setattr(Path, "replace", fail)
        with pytest.raises(OSError, match="disk full"):
            generate.write_atomically(out, "new")
        assert out.read_text() == "old"
        assert list(tmp_path.iterdir()) == [out]


class TestMain:
    @pytest.fixture
    def tofu(self, monkeypatch):
        """Replaces the tofu call; `calls` records the argv, `result` is what it returns."""

        tofu = SimpleNamespace(calls=[], result=subprocess.CompletedProcess([], 0, stdout="{}", stderr=""))

        def run(argv, **kwargs):
            tofu.calls.append(argv)
            return tofu.result

        monkeypatch.setattr(generate.subprocess, "run", run)
        return tofu

    def test_writes_the_inventory_from_the_tofu_output(self, tofu, tmp_path):
        tofu.result = subprocess.CompletedProcess([], 0, stdout=hosts_json(services=SERVICES), stderr="")
        out = tmp_path / "hosts.yaml"
        assert generate.main(["--tofu-dir", str(tmp_path), "--out", str(out)]) == 0
        assert yaml.safe_load(out.read_text())["all"]["hosts"]["services"]["ansible_host"] == "192.168.20.3"
        assert tofu.calls[-1] == ["tofu", f"-chdir={tmp_path}", "output", "-json", "ansible_hosts"]

    def test_a_failed_tofu_call_leaves_the_existing_file(self, tofu, tmp_path, capsys):
        tofu.result = subprocess.CompletedProcess([], 1, stdout="", stderr="no state")
        out = tmp_path / "hosts.yaml"
        out.write_text("old")
        assert generate.main(["--out", str(out)]) == 1
        assert out.read_text() == "old"
        assert "no state" in capsys.readouterr().err

    def test_an_invalid_output_leaves_the_existing_file(self, tofu, tmp_path, capsys):
        tofu.result = subprocess.CompletedProcess([], 0, stdout=hosts_json(Bad=SERVICES), stderr="")
        out = tmp_path / "hosts.yaml"
        out.write_text("old")
        assert generate.main(["--out", str(out)]) == 1
        assert out.read_text() == "old"
        assert "valid inventory host name" in capsys.readouterr().err

    def test_a_missing_tofu_binary_is_reported_without_a_traceback(self, monkeypatch, tmp_path, capsys):
        def run(argv, **kwargs):
            raise FileNotFoundError(2, "No such file", "tofu")

        monkeypatch.setattr(generate.subprocess, "run", run)
        assert generate.main(["--out", str(tmp_path / "hosts.yaml")]) == 1
        assert "not installed" in capsys.readouterr().err
