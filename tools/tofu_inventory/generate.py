"""Writes the Ansible inventory file for the VMs Tofu manages.

Reads the root module's `ansible_hosts` output and writes each VM's address and login user to a
generated inventory file. Group membership and everything else stays in `inventory.yaml`.

    python -m tofu_inventory [--tofu-dir DIR] [--out FILE]
"""

from __future__ import annotations

import argparse
import ipaddress
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml
from utils.repo import PROJECT_ROOT

DEFAULT_TOFU_DIR = PROJECT_ROOT / "tofu"
DEFAULT_OUT = PROJECT_ROOT / "ansible" / "inventory" / "tofu-hosts.yaml"

HOST_NAME_RE = re.compile(r"^[a-z][a-z0-9-]*$")
USER_NAME_RE = re.compile(r"^[a-z_][a-z0-9_-]*$")
ENTRY_KEYS = {"ip_address", "admin_username"}

HEADER = "# Generated by tools/tofu_inventory from the Tofu outputs. Do not edit; rerun the generator.\n"


class InventoryError(Exception):
    """The Tofu output is not a set of entries the inventory can be built from."""


def parse_hosts(raw: str) -> dict[str, dict[str, str]]:
    """Validate the JSON that `tofu output -json ansible_hosts` prints."""
    try:
        hosts = json.loads(raw)
    except json.JSONDecodeError as e:
        raise InventoryError(f"the Tofu output is not JSON: {e}") from e
    if not isinstance(hosts, dict):
        raise InventoryError("ansible_hosts must be an object keyed by host name")
    for name, entry in hosts.items():
        if not HOST_NAME_RE.fullmatch(name):
            raise InventoryError(f"{name!r} is not a valid inventory host name")
        if not isinstance(entry, dict) or set(entry) != ENTRY_KEYS:
            raise InventoryError(f"{name}: entry must have exactly {sorted(ENTRY_KEYS)}")
        address, user = entry["ip_address"], entry["admin_username"]
        try:
            ipaddress.IPv4Address(address)
        except ValueError as e:
            raise InventoryError(f"{name}: ip_address {address!r} is not an IPv4 address") from e
        if not isinstance(user, str) or not USER_NAME_RE.fullmatch(user):
            raise InventoryError(f"{name}: admin_username {user!r} is not a valid login name")
    return hosts


def render(hosts: dict[str, dict[str, str]]) -> str:
    """The inventory file text: hosts sorted by name so a rerun gives the same bytes."""
    body = {"all": {"hosts": {n: {"ansible_host": e["ip_address"], "ansible_user": e["admin_username"]} for n, e in sorted(hosts.items())}}}
    return HEADER + yaml.safe_dump(body, default_flow_style=False, sort_keys=False)


def read_tofu_output(tofu_dir: Path) -> str:
    argv = ["tofu", f"-chdir={tofu_dir}", "output", "-json", "ansible_hosts"]
    try:
        result = subprocess.run(argv, capture_output=True, text=True, check=False)
    except FileNotFoundError as e:
        raise InventoryError("tofu is not installed or not on PATH") from e
    if result.returncode != 0:
        raise InventoryError(f"tofu output failed:\n{result.stderr.strip()}")
    return result.stdout


def write_atomically(path: Path, text: str) -> None:
    """Replace the file in one step, so a failed run never leaves a half-written inventory."""
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
        Path(tmp).replace(path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tofu-dir", type=Path, default=DEFAULT_TOFU_DIR)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    try:
        hosts = parse_hosts(read_tofu_output(args.tofu_dir))
    except InventoryError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    write_atomically(args.out, render(hosts))
    print(f"wrote {len(hosts)} host(s) to {args.out}")
    return 0
